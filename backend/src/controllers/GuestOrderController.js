import Order from "../models/Order.js";
import PendingOrder from "../models/PendingOrder.js";
import User from "../models/Users.js";
import { validateEmail } from "../utils/checkoutValidation.js";
import { presentOrderForGuest } from "../utils/guestAccess.js";
import { GUEST_LINK_INVALID_MESSAGE } from "../middlewares/GuestCheckoutMiddleware.js";

/**
 * Guest order access. A guest can reach an order in exactly two ways:
 *
 *   1. The private link (token) handed to their browser at checkout and shown
 *      on the confirmation page as "Save this link". Full order view.
 *   2. Order number + checkout email. Weaker proof — both can be known to
 *      someone else — so it gets a reduced view with no street address,
 *      postcode or phone, is rate limited per IP and per email, and cannot be
 *      used to claim the order.
 *
 * Every failure returns the same generic message, so neither route can be used
 * to learn whether an order number or email exists.
 *
 * All handlers sit behind resolveGuestToken / validation middleware, so no
 * request value reaches a query untyped.
 */

const NOT_FOUND = { success: false, code: "ORDER_LINK_INVALID", message: GUEST_LINK_INVALID_MESSAGE };
const LOOKUP_NOT_FOUND = {
    success: false,
    code: "ORDER_NOT_FOUND",
    message: "We couldn't find an order matching those details. Check the order number and the email you used at checkout.",
};

/** PHN-<timestamp>-<6 hex>, as generated by the Order model. */
const ORDER_ID_REGEX = /^PHN-\d{10,16}(-[A-F0-9]{6})?$/;

const findOrderByToken = async (tokenHash) => {
    const order = await Order.findOne({ isGuest: true, "guest.accessTokenHash": tokenHash });
    if (!order) return null;
    const expiresAt = order.guest?.accessTokenExpiresAt;
    if (expiresAt && expiresAt.getTime() < Date.now()) return null;
    return order;
};

/* ══════════════════════════════════════════════════════════════
   POST /api/orders/guest/view   { token }
   Also polled by the confirmation page right after payment, so a
   checkout that is paid but not yet turned into an order answers
   202 "processing" rather than "not found".
   ══════════════════════════════════════════════════════════════ */
export const viewGuestOrder = async (req, res) => {
    try {
        const order = await findOrderByToken(req.guestTokenHash);
        if (order) return res.json({ success: true, order: presentOrderForGuest(order) });

        const pending = await PendingOrder.exists({ isGuest: true, "guest.accessTokenHash": req.guestTokenHash });
        if (pending) {
            return res.status(202).json({
                success: false,
                code: "ORDER_PROCESSING",
                message: "We're confirming your payment.",
            });
        }

        return res.status(404).json(NOT_FOUND);
    } catch (error) {
        console.error("viewGuestOrder error:", error?.message || error);
        return res.status(500).json({ success: false, message: "Server error fetching order." });
    }
};

/* ══════════════════════════════════════════════════════════════
   POST /api/orders/guest/lookup   { orderId, email }
   ══════════════════════════════════════════════════════════════ */
export const lookupGuestOrder = async (req, res) => {
    try {
        const rawOrderId = req.body?.orderId;
        const email = validateEmail(req.body?.email);

        const orderId = typeof rawOrderId === "string" ? rawOrderId.trim().toUpperCase() : "";
        if (!ORDER_ID_REGEX.test(orderId) || !email.ok) {
            return res.status(404).json(LOOKUP_NOT_FOUND);
        }

        const order = await Order.findOne({ orderId, isGuest: true, contactEmail: email.value });
        if (!order) return res.status(404).json(LOOKUP_NOT_FOUND);

        return res.json({ success: true, order: presentOrderForGuest(order, { limited: true }) });
    } catch (error) {
        console.error("lookupGuestOrder error:", error?.message || error);
        return res.status(500).json({ success: false, message: "Server error fetching order." });
    }
};

/* ══════════════════════════════════════════════════════════════
   POST /api/orders/guest/claim   { token }   (signed in)

   Attach a guest order to the signed-in account, after which it
   appears under My Orders. Requires BOTH:
     · the private link token — proof the caller placed the order
       (or was given the link by whoever did), and
     · the account's email equals the email used at checkout.
   Account emails are not verified at sign-up, so the email match
   alone proves nothing, which is why guest orders are never
   attached automatically by email.
   ══════════════════════════════════════════════════════════════ */
export const claimGuestOrder = async (req, res) => {
    try {
        const order = await findOrderByToken(req.guestTokenHash);
        if (!order) return res.status(404).json(NOT_FOUND);

        if (order.user) {
            if (order.user.toString() === req.user.id) {
                return res.json({ success: true, alreadyClaimed: true, order: { _id: order._id, orderId: order.orderId } });
            }
            return res.status(409).json({
                success: false,
                code: "ORDER_ALREADY_CLAIMED",
                message: "This order is already linked to an account.",
            });
        }

        const account = await User.findById(req.user.id).select("email");
        if (!account) return res.status(404).json({ success: false, message: "User not found." });

        if (!order.contactEmail || account.email.toLowerCase() !== order.contactEmail) {
            return res.status(403).json({
                success: false,
                code: "EMAIL_MISMATCH",
                message: "This order was placed with a different email address. Sign in with that email to add it to your account.",
            });
        }

        /* Conditional on still being unclaimed, so two concurrent claims can't
           both succeed. */
        const claimed = await Order.findOneAndUpdate(
            { _id: order._id, isGuest: true, user: null },
            { $set: { user: account._id, "guest.claimedAt": new Date() } },
            { new: true }
        );
        if (!claimed) {
            return res.status(409).json({
                success: false,
                code: "ORDER_ALREADY_CLAIMED",
                message: "This order is already linked to an account.",
            });
        }

        return res.json({ success: true, order: { _id: claimed._id, orderId: claimed.orderId } });
    } catch (error) {
        console.error("claimGuestOrder error:", error?.message || error);
        return res.status(500).json({ success: false, message: "Server error linking order." });
    }
};
